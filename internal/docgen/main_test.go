package main

import (
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"
)

func mustRead(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v", path, err)
	}
	return string(b)
}

func TestGenerate(t *testing.T) {
	out := t.TempDir()
	if err := generate(out); err != nil {
		t.Fatalf("generate: %v", err)
	}
	read := func(t *testing.T, name string) string {
		t.Helper()
		return mustRead(t, filepath.Join(out, name))
	}

	t.Run("one page per command, named after git zf", func(t *testing.T) {
		for _, f := range []string{"git_zf.md", "git_zf_issue.md", "git_zf_issue_start.md", "git_zf_review_approve.md", "git_zf_branch_close.md"} {
			if _, err := os.Stat(filepath.Join(out, f)); err != nil {
				t.Errorf("%s: %v", f, err)
			}
		}
	})

	t.Run("skips hidden commands", func(t *testing.T) {
		for _, f := range []string{"git_zf_review_guard.md", "git_zf_review_guard-commit.md"} {
			if _, err := os.Stat(filepath.Join(out, f)); err == nil {
				t.Errorf("%s exists", f)
			}
		}
	})

	t.Run("front matter carries title and sidebar label", func(t *testing.T) {
		got := read(t, "git_zf_issue_start.md")
		for _, want := range []string{"---\ntitle: \"git zf issue start\"\nsidebar_label: \"issue start\"\n---\n", "## git zf issue start"} {
			if !strings.Contains(got, want) {
				t.Errorf("git_zf_issue_start.md lacks %q", want)
			}
		}
	})

	t.Run("root page is labelled git zf", func(t *testing.T) {
		if got := read(t, "git_zf.md"); !strings.Contains(got, "sidebar_label: \"git zf\"") {
			t.Errorf("root label: %q", got[:min(120, len(got))])
		}
	})

	t.Run("no auto-generated footer", func(t *testing.T) {
		entries, _ := os.ReadDir(out)
		for _, e := range entries {
			if strings.Contains(read(t, e.Name()), "Auto generated by spf13/cobra") {
				t.Errorf("%s has the cobra footer", e.Name())
			}
		}
	})

	t.Run("see-also links point at sibling pages", func(t *testing.T) {
		got := read(t, "git_zf_issue_start.md")
		if !strings.Contains(got, "](git_zf_issue.md)") {
			t.Errorf("no link to git_zf_issue.md in see-also:\n%s", got)
		}
	})

	t.Run("angle-bracket placeholders survive in prose", func(t *testing.T) {
		got := read(t, "git_zf_review_approve.md")
		if !strings.Contains(got, "&lt;IssueID&gt;@review") {
			t.Errorf("git_zf_review_approve.md: <IssueID> is not escaped in prose; it renders as an empty element")
		}
		if strings.Contains(got, "<IssueID>") {
			t.Errorf("git_zf_review_approve.md: a bare <IssueID> remains")
		}
	})

	t.Run("code fences keep their angle brackets", func(t *testing.T) {
		got := read(t, "git_zf_issue_close.md")
		if !strings.Contains(got, "git zf issue close [<id>] [flags]") {
			t.Errorf("git_zf_issue_close.md: the usage fence was escaped")
		}
	})

	t.Run("no bare tag-like text outside fences on any page", func(t *testing.T) {
		bare := regexp.MustCompile(`<[A-Za-z]`)
		entries, _ := os.ReadDir(out)
		for _, e := range entries {
			inFence := false
			for i, line := range strings.Split(read(t, e.Name()), "\n") {
				if strings.HasPrefix(line, "```") {
					inFence = !inFence
					continue
				}
				if !inFence && bare.MatchString(line) {
					t.Errorf("%s:%d: %q", e.Name(), i+1, line)
				}
			}
		}
	})

	t.Run("a stale page is removed", func(t *testing.T) {
		stale := filepath.Join(out, "git_zf_gone.md")
		if err := os.WriteFile(stale, []byte("x"), 0o644); err != nil {
			t.Fatal(err)
		}
		if err := generate(out); err != nil {
			t.Fatal(err)
		}
		if _, err := os.Stat(stale); err == nil {
			t.Error("git_zf_gone.md survived a regeneration")
		}
	})

	t.Run("ignores the user config", func(t *testing.T) {
		home := t.TempDir()
		cfg := "[branch]\nbase = \"zzz\"\n[[commit-types]]\nname = \"zzz\"\ndesc = \"zzz\"\n"
		if err := os.WriteFile(filepath.Join(home, ".git-zf.toml"), []byte(cfg), 0o644); err != nil {
			t.Fatal(err)
		}
		t.Setenv("HOME", home)
		again := t.TempDir()
		if err := generate(again); err != nil {
			t.Fatal(err)
		}
		entries, _ := os.ReadDir(out)
		for _, e := range entries {
			if a, b := read(t, e.Name()), mustRead(t, filepath.Join(again, e.Name())); a != b {
				t.Errorf("%s depends on $HOME/.git-zf.toml", e.Name())
			}
		}
	})
}

func TestGenerate_MatchesCommitted(t *testing.T) {
	out := t.TempDir()
	if err := generate(out); err != nil {
		t.Fatal(err)
	}
	committed := filepath.Join("..", "..", "website", "docs", "reference", "commands")

	t.Run("committed reference pages are up to date", func(t *testing.T) {
		names := func(dir string) map[string]bool {
			set := map[string]bool{}
			entries, err := os.ReadDir(dir)
			if err != nil {
				t.Fatalf("read %s: %v", dir, err)
			}
			for _, e := range entries {
				if strings.HasSuffix(e.Name(), ".md") {
					set[e.Name()] = true
				}
			}
			return set
		}
		fresh, old := names(out), names(committed)
		for name := range fresh {
			if !old[name] {
				t.Errorf("%s is missing: run make docs-gen", name)
				continue
			}
			if mustRead(t, filepath.Join(out, name)) != mustRead(t, filepath.Join(committed, name)) {
				t.Errorf("%s differs: run make docs-gen", name)
			}
		}
		for name := range old {
			if !fresh[name] {
				t.Errorf("%s is stale: run make docs-gen", name)
			}
		}
	})
}
